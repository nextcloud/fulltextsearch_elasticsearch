namespace OCA\FullTextSearch_Elasticsearch\Service;

use OCA\FullTextSearch_Elasticsearch\ConfigLexicon;
use OCA\FullTextSearch_Elasticsearch\Exceptions\AccessIsEmptyException;
use OCA\FullTextSearch_Elasticsearch\Exceptions\ConfigurationException;
use OCA\FullTextSearch_Elasticsearch\Model\IngestPipelineStatus;
use OCA\FullTextSearch_Elasticsearch\Tools\Traits\TArrayTools;
use OCA\FullTextSearch_Elasticsearch\Vendor\Elastic\Elasticsearch\Client;
use OCA\FullTextSearch_Elasticsearch\Vendor\Elastic\Elasticsearch\Exception\ClientResponseException;
use OCA\FullTextSearch_Elasticsearch\Vendor\Elastic\Elasticsearch\Exception\MissingParameterException;
use OCA\FullTextSearch_Elasticsearch\Vendor\Elastic\Elasticsearch\Exception\ServerResponseException;
use OCA\FullTextSearch_Elasticsearch\Vendor8\Elastic\Elasticsearch\Client as Client8;
use OCA\FullTextSearch_Elasticsearch\Vendor8\Elastic\Elasticsearch\Exception\ClientResponseException as ClientResponseException8;
use OCA\FullTextSearch_Elasticsearch\Vendor8\Elastic\Elasticsearch\Exception\MissingParameterException as MissingParameterException8;
use OCA\FullTextSearch_Elasticsearch\Vendor8\Elastic\Elasticsearch\Exception\ServerResponseException as ServerResponseException8;
use OCP\AppFramework\Services\IAppConfig;
use OCP\FullTextSearch\Model\IIndex;
use OCP\FullTextSearch\Model\IIndexDocument;
use Psr\Log\LoggerInterface;

class IndexService {

	use TArrayTools;

	public function __construct(
		private IndexMappingService $indexMappingService,
		private readonly IAppConfig $appConfig,
		private LoggerInterface $logger,
	) {
	}

	/**
	 * @param Client|Client8 $client
	 *
	 * @return bool
	 * @throws ClientResponseException|ClientResponseException8
	 * @throws ConfigurationException
	 * @throws MissingParameterException|MissingParameterException8
	 * @throws ServerResponseException|ServerResponseException8
	 */
	public function testIndex(Client|Client8 $client): bool {
		$map = $this->indexMappingService->generateGlobalMap(false);
		$map['client'] = [
			'verbose' => true
		];

		$result = $client->indices()
			->exists($map);

		return $result->asBool();
	}

	/**
	 * @param Client|Client8 $client
	 *
	 * @throws ConfigurationException
	 * @throws MissingParameterException|MissingParameterException8
	 * @throws ServerResponseException|ServerResponseException8
	 */
	public function initializeIndex(Client|Client8 $client): void {
		try {
			if ($client->indices()
				->exists($this->indexMappingService->generateGlobalMap(false))
				->asBool()) {
				$this->updateIngestPipeline($client);
				return;
			}
		} catch (ClientResponseException|ClientResponseException8 $e) {
			$this->logger->error($e->getMessage(), ['exception' => $e]);
		}

		try {
			$client->indices()
				->create($this->indexMappingService->generateGlobalMap());
		} catch (ClientResponseException|ClientResponseException8 $e) {
			$this->logger->error('reset index all', ['exception' => $e]);
			$this->resetIndexAll($client);
		}

		try {
			$client->ingest()
				->putPipeline($this->indexMappingService->generateGlobalIngest());
		} catch (ClientResponseException|ClientResponseException8 $e) {
			$this->logger->error('reset index all', ['exception' => $e]);
			$this->resetIndexAll($client);
		}
	}

	/**
	 * replace the ingest pipeline if it is missing or older than the one generated by this version
	 *
	 * @param Client|Client8 $client
	 *
	 * @throws ClientResponseException|ClientResponseException8
	 * @throws MissingParameterException|MissingParameterException8
	 * @throws ServerResponseException|ServerResponseException8
	 */
	private function updateIngestPipeline(Client|Client8 $client): void {
		$status = $this->getIngestPipelineStatus($client);
		if ($status === IngestPipelineStatus::CURRENT) {
			return;
		}

		if ($status === IngestPipelineStatus::INCOMPATIBLE) {
			$this->appConfig->setAppValueBool(ConfigLexicon::REINDEX_REQUIRED, true);
			$this->logger->warning(
				'The ingest pipeline on Elasticsearch has been updated, existing documents need to be indexed again using '
				. '"occ fulltextsearch:index \'{"force":true}\'"'
			);
		}

		$client->ingest()
			->putPipeline($this->indexMappingService->generateGlobalIngest());
	}

	/**
	 * @param Client|Client8 $client
	 *
	 * @return IngestPipelineStatus
	 * @throws ClientResponseException|ClientResponseException8
	 * @throws MissingParameterException|MissingParameterException8
	 * @throws ServerResponseException|ServerResponseException8
	 */
	public function getIngestPipelineStatus(Client|Client8 $client): IngestPipelineStatus {
		try {
			$result = $client->ingest()
				->getPipeline($this->indexMappingService->generateGlobalIngest(false))
				->asArray();
		} catch (ClientResponseException|ClientResponseException8 $e) {
			if ($e->getCode() === 404) {
				return IngestPipelineStatus::MISSING;
			}

			throw $e;
		}

		$pipeline = $result[IndexMappingService::INGEST_PIPELINE_ID] ?? null;
		if (!is_array($pipeline)) {
			return IngestPipelineStatus::MISSING;
		}

		if ($this->indexMappingService->isIngestPipelineIncompatible($pipeline)) {
			return IngestPipelineStatus::INCOMPATIBLE;
		}

		if (($pipeline['version'] ?? 0) < IndexMappingService::INGEST_PIPELINE_VERSION) {
			return IngestPipelineStatus::OUTDATED;
		}

		return IngestPipelineStatus::CURRENT;
	}

	/**
	 * count documents that went through the ingest pipeline, but not through the current one
	 *
	 * @param Client|Client8 $client
	 *
	 * @return int
	 * @throws ConfigurationException
	 * @throws ClientResponseException|ClientResponseException8
	 * @throws ServerResponseException|ServerResponseException8
	 */
	public function countDocumentsFromOutdatedPipeline(Client|Client8 $client): int {
		$params = $this->indexMappingService->generateGlobalMap(false);
		$params['body'] = [
			'query' => [
				'bool' => [
					'filter' => [
						['exists' => ['field' => 'attachment']]
					],
					'must_not' => [
						[
							'range' => [
								IndexMappingService::INGEST_PIPELINE_VERSION_FIELD => [
									'gte' => IndexMappingService::INGEST_PIPELINE_VERSION
								]
							]
						]
					]
				]
			]
		];

		$result = $client->count($params)->asArray();

		return (int)($result['count'] ?? 0);
	}

	/**
	 * @param Client|Client8 $client
	 * @param string $providerId
	 *
	 * @throws ConfigurationException
	 */
	public function resetIndex(Client|Client8 $client, string $providerId): void {
		try {
			$client->deleteByQuery($this->indexMappingService->generateDeleteQuery($providerId));
		} catch (ClientResponseException|ClientResponseException8 $e) {
			$this->logger->error('reset index all', ['exception' => $e]);
		}
	}

	/**
	 * @param Client|Client8 $client
	 *
	 * @throws ConfigurationException
	 * @throws MissingParameterException|MissingParameterException8
	 * @throws ServerResponseException|ServerResponseException8
	 */
	public function resetIndexAll(Client|Client8 $client): void {
		$this->appConfig->deleteAppValue(ConfigLexicon::REINDEX_REQUIRED);

		try {
			$client->ingest()
				->deletePipeline($this->indexMappingService->generateGlobalIngest(false));
		} catch (ClientResponseException|ClientResponseException8 $e) {
			$this->logger->warning($e->getMessage(), ['exception' => $e]);
		}

		try {
			$client->indices()
				->delete($this->indexMappingService->generateGlobalMap(false));
		} catch (ClientResponseException|ClientResponseException8 $e) {
			$this->logger->warning($e->getMessage(), ['exception' => $e]);
		}
	}

	/**
	 * @param Client|Client8 $client
	 * @param IIndex $index
	 *
	 * @throws ConfigurationException
	 */
	public function deleteIndex(Client|Client8 $client, IIndex $index): void {
		$this->indexMappingService->indexDocumentRemove(
			$client,
			$index->getProviderId(),
			$index->getDocumentId()
		);
	}

	/**
	 * @param Client|Client8 $client
	 * @param IIndexDocument $document
	 *
	 * @return array
	 * @throws ConfigurationException
	 * @throws AccessIsEmptyException
	 */
	public function indexDocument(Client|Client8 $client, IIndexDocument $document): array {
		$result = [];
		$index = $document->getIndex();
		if ($index->isStatus(IIndex::INDEX_REMOVE)) {
			$this->indexMappingService->indexDocumentRemove(
				$client, $document->getProviderId(), $document->getId()
			);
		} elseif ($index->isStatus(IIndex::INDEX_OK) && !$index->isStatus(IIndex::INDEX_CONTENT)
				   && !$index->isStatus(IIndex::INDEX_META)) {
			$result = $this->indexMappingService->indexDocumentUpdate($client, $document);
		} else {
			$result = $this->indexMappingService->indexDocumentNew($client, $document);
		}

		return $result;
	}

	/**
	 * @param IIndex $index
	 * @param array $result
	 *
	 * @return IIndex
	 */
	public function parseIndexResult(IIndex $index, array $result): IIndex {
		$index->setLastIndex();

		if (array_key_exists('exception', $result)) {
			$index->setStatus(IIndex::INDEX_FAILED);
			$index->addError(
				$this->get('message', $result, $result['exception']),
				'',
				IIndex::ERROR_SEV_3
			);

			return $index;
		}

		// TODO: parse result
		if ($index->getErrorCount() === 0) {
			$index->setStatus(IIndex::INDEX_DONE);
		}

		return $index;
	}
}
